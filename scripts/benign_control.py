"""Benign control for the six payload attacks, including base64.

On injected documents, several attacks raise recall instead of lowering it
(ProtectAI's base64 recall rises from 0.708 to 0.975). That is only detection
if the same transformation applied to harmless text does not also get flagged.
This script takes the 200 benign test documents that contain a harmless insert
(benign imperatives and benign prompts), applies each attack to the insert
only, and measures the false-positive rate. It extends the corrupted-benign
control in scripts/extra_indirect.py from two attacks to all six.

The base64 attack wraps the payload as "decode this: <base64>", and the prefix
is itself an instruction. A second variant, base64_raw, inserts the encoded
text alone, to separate the encoding from the instruction. base64_raw is also
applied to the injected documents so that it has a matching recall; recall for
the other attacks comes from adversarial.csv / baseline_adversarial.csv.

Scoring: chunk (maximum over ~400-character windows) and chunk_decode (base64
runs decoded and appended first), threshold 0.5, same seeds as the
adversarial suite (42 + row index).

Run:
  python -m scripts.benign_control --models baseline   # ProtectAI (GPU recommended)
  python -m scripts.benign_control --models study      # the six study models
Each run writes results/indirect/benign_control_<models>.csv; benign_control.md
is rebuilt from whichever of the two CSVs exist.
"""
import argparse
import base64
import os

import pandas as pd

from scripts.eval_indirect import (ATTACKS, THRESHOLD, ScoreCache, chunk_decode_scores,
                                   chunk_scores)

OUT = "results/indirect"
MODES = {"chunk": chunk_scores, "chunk_decode": chunk_decode_scores}


def base64_raw(text, seed=None):
    """The payload as base64 with no surrounding instruction."""
    return base64.b64encode(text.encode("utf-8")).decode("ascii")


VARIANTS = {**ATTACKS, "base64_raw": base64_raw}


def apply(df, fn):
    return [r.text if fn is None else r.text.replace(r.payload, fn(r.payload, seed=42 + i), 1)
            for i, r in df.iterrows()]


def load_scorers(group):
    if group == "baseline":
        from scripts.eval_baseline import BASELINES, hf_scorer
        return {k: hf_scorer(repo) for k, repo in BASELINES.items()}
    from src.indirect.models import load_all
    return load_all()


def recall_lookup(group):
    path = f"{OUT}/baseline_adversarial.csv" if group == "baseline" else f"{OUT}/adversarial.csv"
    adv = pd.read_csv(path)
    return adv.set_index(["attack", "model", "mode"]).recall.to_dict()


def run(group):
    df = pd.read_csv("data/indirect/test.csv")
    df["text"] = df["text"].astype(str)
    has_insert = df.payload.notna() & (df.payload.astype(str).str.len() > 0)
    ben = df[(df.label == 0) & has_insert].reset_index(drop=True)
    inj = df[(df.label == 1) & has_insert].reset_index(drop=True)
    ben["payload"], inj["payload"] = ben.payload.astype(str), inj.payload.astype(str)

    scorers = load_scorers(group)
    caches = {k: ScoreCache(s) for k, s in scorers.items()}
    known = recall_lookup(group)
    raw_injected = apply(inj, base64_raw)

    rows = []
    for variant, fn in VARIANTS.items():
        texts = apply(ben, fn)
        for name in scorers:
            for mode, score in MODES.items():
                fpr = float((score(caches[name], texts) >= THRESHOLD).mean())
                if variant == "base64_raw":
                    recall = float((score(caches[name], raw_injected) >= THRESHOLD).mean())
                else:
                    recall = known.get((variant, name, mode), float("nan"))
                rows.append({"variant": variant, "model": name, "mode": mode, "n_benign": len(ben),
                             "fpr_benign": fpr, "n_injected": len(inj), "recall_injected": recall})
                print(f"{variant:20s} {name:15s} {mode:12s} FPR {fpr:.3f}  recall {recall:.3f}")
    out = pd.DataFrame(rows)
    out.to_csv(f"{OUT}/benign_control_{group}.csv", index=False)
    return out


def write_markdown():
    parts = [pd.read_csv(p) for p in (f"{OUT}/benign_control_study.csv", f"{OUT}/benign_control_baseline.csv")
             if os.path.exists(p)]
    if not parts:
        return
    from scripts.eval_baseline import BASELINE_LABELS
    from src.indirect.models import MODEL_LABELS
    names = {**MODEL_LABELS, **BASELINE_LABELS}
    d = pd.concat(parts, ignore_index=True)
    intro = ("Generated by `python -m scripts.benign_control`. Each attack is applied to the harmless insert of the "
             f"{int(d.n_benign.iloc[0])} benign test documents that have one, and to the payload of the "
             f"{int(d.n_injected.iloc[0])} injected test documents. If an attack raises the false-positive rate on "
             "benign documents about as much as it raises recall on injected ones, the recall gain is a shortcut "
             "(the transformation itself looks suspicious), not detection. `base64_encoding` inserts "
             "`decode this: <base64>`; `base64_raw` inserts the base64 text alone. Threshold 0.5.")
    lines = ["# Benign control for the payload attacks", "", intro, ""]
    for mode in ["chunk", "chunk_decode"]:
        lines += [f"## Mode: {mode}", "", "| variant | model | FPR on benign | recall on injected |", "|---|---|---|---|"]
        for r in d[d["mode"] == mode].itertuples():
            lines.append(f"| {r.variant} | {names.get(r.model, r.model)} | {r.fpr_benign:.3f} | {r.recall_injected:.3f} |")
        lines.append("")
    with open(f"{OUT}/benign_control.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", choices=["baseline", "study"], default="baseline")
    args = ap.parse_args()
    run(args.models)
    write_markdown()
    print(f"Saved {OUT}/benign_control_{args.models}.csv and {OUT}/benign_control.md")


if __name__ == "__main__":
    main()
