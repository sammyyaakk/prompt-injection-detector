"""Outside baseline: a public prompt-injection detector on the indirect benchmark.

Scores ProtectAI's deberta-v3-base-prompt-injection-v2 (inference only, no
retraining) with exactly the protocol of scripts/eval_indirect.py: the same
four test sets, the same doc / chunk / chunk_decode scoring, the same six
attacks on the embedded payload, the same breakdowns and the same localisation
test. It writes separate baseline_* files and leaves the study's own results
untouched, then puts the baseline next to the six study models in one table.

Run: python -m scripts.eval_baseline
"""
import os
import time

import numpy as np
import pandas as pd
import torch
from transformers import AutoModelForSequenceClassification, AutoTokenizer

from scripts.eval_indirect import (ScoreCache, load_test_sets, md_table, run_adversarial,
                                   run_breakdowns, run_localisation, run_main)
from src.indirect.models import MODEL_LABELS

OUT = "results/indirect"
BASELINES = {"protectai_v2": "protectai/deberta-v3-base-prompt-injection-v2"}
BASELINE_LABELS = {"protectai_v2": "ProtectAI DeBERTa-v3 v2 (public, not retrained)"}
MAX_LENGTH = 512
BATCH_SIZE = 16


def hf_scorer(repo):
    """P(injection) from a HuggingFace sequence classifier, found by label name."""
    device = "cuda" if torch.cuda.is_available() else "cpu"
    tokenizer = AutoTokenizer.from_pretrained(repo)
    model = AutoModelForSequenceClassification.from_pretrained(repo).to(device).eval()
    labels = {v.upper(): k for k, v in model.config.id2label.items()}
    pos = labels["INJECTION"]

    def score(texts):
        probs = []
        with torch.no_grad():
            for i in range(0, len(texts), BATCH_SIZE):
                enc = tokenizer(list(texts[i:i + BATCH_SIZE]), truncation=True, padding=True,
                                max_length=MAX_LENGTH, return_token_type_ids=False,
                                return_tensors="pt").to(device)
                probs.extend(torch.softmax(model(**enc).logits, dim=-1)[:, pos].cpu().tolist())
        return np.array(probs)

    return score


def revision_of(repo):
    """Commit hash of the snapshot actually loaded (works offline from the cache)."""
    try:
        from huggingface_hub import snapshot_download
        return os.path.basename(snapshot_download(repo, local_files_only=True))
    except Exception:
        try:
            from huggingface_hub import model_info
            return model_info(repo).sha
        except Exception as exc:
            return f"unknown ({type(exc).__name__})"


def comparison(base_main):
    """Indirect-test rows for the six study models and the baseline, chunk and doc modes."""
    study = pd.read_csv(f"{OUT}/main_results.csv")
    both = pd.concat([study, base_main], ignore_index=True)
    d = both[(both.test_set == "indirect_test") & (both["mode"].isin(["doc", "chunk"]))].copy()
    names = {**MODEL_LABELS, **BASELINE_LABELS}
    d["model"] = d.model.map(names)
    return d[["model", "mode", "precision", "recall", "f1", "fpr", "auroc"]]


def write_markdown(base_main, cmp, br, adv, loc, revisions, seconds):
    lines = [
        "# Outside baseline on the indirect benchmark",
        "",
        "Generated by `python -m scripts.eval_baseline`. Inference only: the public model is not retrained. "
        "Same protocol as `scripts/eval_indirect.py` (threshold 0.5; `doc` = whole document, `chunk` = "
        "maximum over ~400-character windows, `chunk_decode` = decode base64 runs first).",
        "",
        "Models: " + "; ".join(f"`{BASELINES[k]}` (revision `{revisions[k]}`)" for k in BASELINES),
        "",
        f"Scoring time on this machine: {seconds:.0f} s.",
        "",
        "## Indirect test (n=800): baseline next to the study models",
        "",
        md_table(cmp),
        "",
        "## All test sets (baseline)",
        "",
        md_table(base_main[["test_set", "mode", "precision", "recall", "f1", "fpr", "auroc"]]),
        "",
        "## Indirect test breakdowns (baseline, chunk mode)",
        "",
        md_table(br[br["mode"] == "chunk"][["dimension", "value", "metric", "n", "score"]]),
        "",
        "## Adversarial: recall on 400 injected test documents (baseline)",
        "",
        md_table(adv[["attack", "mode", "recall", "recall_drop"]]),
        "",
        "## Localisation: is the top-scoring window the injected payload? (baseline)",
        "",
        md_table(loc.drop(columns=["model"])),
        "",
    ]
    with open(f"{OUT}/baseline_results.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    os.makedirs(OUT, exist_ok=True)
    sets = load_test_sets()
    revisions = {k: revision_of(repo) for k, repo in BASELINES.items()}
    scorers = {k: hf_scorer(repo) for k, repo in BASELINES.items()}
    caches = {k: ScoreCache(s) for k, s in scorers.items()}

    start = time.perf_counter()
    base_main = run_main(scorers, caches, sets)
    df = sets["indirect_test"]
    br = run_breakdowns(scorers, df)
    adv = run_adversarial(scorers, caches, df)
    loc = run_localisation(scorers, caches, df)
    seconds = time.perf_counter() - start

    base_main.to_csv(f"{OUT}/baseline_main_results.csv", index=False)
    br.to_csv(f"{OUT}/baseline_breakdowns.csv", index=False)
    adv.to_csv(f"{OUT}/baseline_adversarial.csv", index=False)
    loc.to_csv(f"{OUT}/baseline_localisation.csv", index=False)
    score_cols = ["doc_id", "label"] + [c for c in df.columns if c.startswith("p_")]
    df[score_cols].to_csv(f"{OUT}/baseline_test_scores.csv", index=False)

    cmp = comparison(base_main)
    write_markdown(base_main, cmp, br, adv, loc, revisions, seconds)
    print(md_table(cmp))
    print(f"Saved {OUT}/baseline_results.md and baseline_*.csv ({seconds:.0f} s)")


if __name__ == "__main__":
    main()
