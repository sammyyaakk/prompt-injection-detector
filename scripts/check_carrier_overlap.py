"""Check whether any carrier document is used in both the training and test splits.

BIPIA's own email train and test files share some emails, and the benchmark
builder takes carriers from each split's file, so a shared email can carry a
training document and a test document. Injection texts, framing templates and
harmless lines never overlap (checked here too); only the surrounding carrier
text can. This script counts the affected test documents and recomputes the
window-mode metrics of the three document-trained models without them.

Writes results/indirect/carrier_overlap.md
Run: python -m scripts.check_carrier_overlap
"""
import json

import pandas as pd
from sklearn.metrics import f1_score

from scripts.build_indirect_benchmark import BIPIA_DIR, CARRIERS_PER_TYPE, _load_jsonl

OUT = "results/indirect/carrier_overlap.md"
THRESHOLD = 0.5


def carriers(split, kind):
    records = _load_jsonl(f"{BIPIA_DIR}/{kind}_{split}.jsonl")[:CARRIERS_PER_TYPE[split][kind]]
    return [json.dumps(r.get("context"), sort_keys=True) for r in records]


def main():
    lines = ["# Carrier overlap between the training and test splits", "",
             "Generated by `python -m scripts.check_carrier_overlap`.", "",
             "| carrier | distinct in train | distinct in test | in both |", "|---|---|---|---|"]
    shared_idx = {}
    for kind in ["email", "table", "code"]:
        train, test = carriers("train", kind), carriers("test", kind)
        both = set(train) & set(test)
        shared_idx[kind] = {i for i, c in enumerate(test) if c in both}
        lines.append(f"| {kind} | {len(set(train))} | {len(set(test))} | {len(both)} |")

    tr, te = pd.read_csv("data/indirect/train.csv"), pd.read_csv("data/indirect/test.csv")
    lines += ["", (f"Injection texts in both splits: {len(set(tr.payload.dropna()) & set(te.payload.dropna()))}. "
                   f"Framing templates in both splits: {len(set(tr.template.dropna()) & set(te.template.dropna()))}."),
              ""]

    s = pd.read_csv("results/indirect/indirect_test_scores.csv")
    parts = s.doc_id.str.split(":")
    s["shared"] = [int(i) in shared_idx[k] for k, i in zip(parts.str[1], parts.str[2])]
    lines += [(f"Test documents built on a carrier that also appears in training: {int(s.shared.sum())} of {len(s)} "
               f"({int(s[s.shared].label.sum())} injected)."), "",
              "Window-mode metrics with and without those documents:", "",
              "| model | test documents | F1 | recall | FPR |", "|---|---|---|---|---|"]
    for model in ["tfidf_ind", "embedding_ind", "distilbert_ind"]:
        for name, d in [("all", s), ("excluding shared carriers", s[~s.shared])]:
            pred = (d[f"p_{model}_chunk"] >= THRESHOLD).astype(int)
            lines.append(f"| {model} | {name} ({len(d)}) | {f1_score(d.label, pred):.3f} | "
                         f"{pred[d.label == 1].mean():.3f} | {pred[d.label == 0].mean():.3f} |")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
